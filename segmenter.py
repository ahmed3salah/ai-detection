"""
Python port of Modules/Core/app/Services/AiDetection/Segmentation/ManuscriptSegmenter.php.

Training paragraphs have to be cut the way production cuts them, or the model is evaluated on
a shape of text it never sees. tests/fixtures/segmenter holds expected output generated by the
PHP original, and both repos test against it. Change the two together.
"""
import re
import xml.etree.ElementTree as ET
from dataclasses import dataclass, replace
from typing import List, Optional

import regex

MERGE_BELOW_WORDS = 40
SPLIT_ABOVE_WORDS = 300
TARGET_WORDS = 180
MIN_SCORABLE_WORDS = 20

KIND_ABSTRACT = "abstract"
KIND_PARAGRAPH = "paragraph"

_TEI = "{http://www.tei-c.org/ns/1.0}"
_NON_PROSE = {"figure", "table", "formula", "note", "listBibl", "biblStruct"}

_BACK_MATTER_HEADING = re.compile(r"^\s*(?:\d+\.?\s*)?(references|bibliography|works cited|literature cited)\s*$", re.I | re.M)
_SENTENCE_BREAK = regex.compile(r"(?<=[.!?])\s+(?=[\p{Lu}\d(\[])")
_BROKEN_WORD = regex.compile(r"(\p{L})-\n(\p{Ll})")


@dataclass(frozen=True)
class Segment:
    kind: str
    text: str
    section: Optional[str] = None
    coords: Optional[str] = None


def count_words(text: str) -> int:
    return len(text.split())


def _local_name(element: ET.Element) -> str:
    return element.tag.rsplit("}", 1)[-1] if isinstance(element.tag, str) else ""


def _prose_of(element: ET.Element) -> str:
    """Text of an element without the non-prose elements inside it, as the PHP's textOf does."""
    text = element.text or ""
    for child in element:
        text += " " if _local_name(child) in _NON_PROSE else _prose_of(child)
        text += child.tail or ""
    return text


def _section_title(head: ET.Element) -> Optional[str]:
    title = " ".join("".join(head.itertext()).split())
    if not title:
        return None
    return f"{head.get('n', '').strip()} {title}".strip()[:255]


def from_tei(xml: str) -> List[Segment]:
    """The abstract and the body's paragraphs, under their headings, from GROBID's full-text TEI."""
    try:
        root = ET.fromstring(xml)
    except ET.ParseError:
        return []

    segments: List[Segment] = []
    for abstract in root.iter(f"{_TEI}abstract"):
        for paragraph in abstract.iter(f"{_TEI}p"):
            segments.append(Segment(KIND_ABSTRACT, _prose_of(paragraph), "Abstract", paragraph.get("coords") or None))

    for body in root.iter(f"{_TEI}body"):
        _walk_body(body, None, segments)

    return normalize_segments(segments)


def _walk_body(element: ET.Element, section: Optional[str], segments: List[Segment]) -> None:
    """Paragraphs in document order, each under the nearest enclosing div that has a heading."""
    if _local_name(element) == "div":
        head = element.find(f"{_TEI}head")
        if head is not None:
            # The nearest heading decides, even an empty one: section becomes null, as in the PHP.
            section = _section_title(head)
    for child in element:
        name = _local_name(child)
        if name in _NON_PROSE:
            continue
        if name == "p":
            segments.append(Segment(KIND_PARAGRAPH, _prose_of(child), section, child.get("coords") or None))
        _walk_body(child, section, segments)


def from_text(text: str) -> List[Segment]:
    """Pasted text, or a PDF GROBID couldn't read: blank lines separate paragraphs."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")

    # Offsets in UTF-8 bytes, as PHP's PREG_OFFSET_CAPTURE and strlen count them.
    matches = list(_BACK_MATTER_HEADING.finditer(text))
    if matches:
        last = matches[-1]
        if len(text[: last.start()].encode()) > len(text.encode()) / 3:
            text = text[: last.start()]

    return normalize_segments(
        [Segment(KIND_PARAGRAPH, _BROKEN_WORD.sub(r"\1\2", block)) for block in re.split(r"\n\s*\n", text)]
    )


def normalize_segments(segments: List[Segment]) -> List[Segment]:
    cleaned = []
    for segment in segments:
        text = " ".join(segment.text.split())
        if text:
            cleaned.append(replace(segment, text=text))

    result: List[Segment] = []
    for segment in _merge_short(cleaned):
        result.extend(_split_long(segment))
    return result


def _same_block(a: Segment, b: Segment) -> bool:
    return a.kind == b.kind and a.section == b.section


def _merge_short(segments: List[Segment]) -> List[Segment]:
    merged: List[Segment] = []
    carry: Optional[Segment] = None

    for segment in segments:
        if carry is not None:
            if _same_block(carry, segment):
                segment = Segment(segment.kind, f"{carry.text} {segment.text}", segment.section, carry.coords or segment.coords)
            else:
                merged = _append_or_join(merged, carry)
            carry = None

        if count_words(segment.text) < MERGE_BELOW_WORDS:
            carry = segment
            continue
        merged.append(segment)

    return _append_or_join(merged, carry) if carry is not None else merged


def _append_or_join(merged: List[Segment], short: Segment) -> List[Segment]:
    if merged and _same_block(merged[-1], short) and count_words(merged[-1].text) < SPLIT_ABOVE_WORDS:
        merged[-1] = replace(merged[-1], text=f"{merged[-1].text} {short.text}")
        return merged
    merged.append(short)
    return merged


def _split_long(segment: Segment) -> List[Segment]:
    if count_words(segment.text) <= SPLIT_ABOVE_WORDS:
        return [segment]

    pieces: List[str] = []
    current = ""
    for sentence in _SENTENCE_BREAK.split(segment.text):
        candidate = sentence if current == "" else f"{current} {sentence}"
        if current != "" and count_words(candidate) > TARGET_WORDS:
            pieces.append(current)
            current = sentence
            continue
        current = candidate

    if current != "":
        if pieces and count_words(current) < MERGE_BELOW_WORDS:
            pieces[-1] = f"{pieces[-1]} {current}"
        else:
            pieces.append(current)

    return [replace(segment, text=piece) for piece in pieces]
